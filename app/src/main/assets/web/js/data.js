function transliterate(ar) {
  // Strip tashkeel (harakat) before dictionary lookup so vowelled words
  // like "جَمَل" still match the undiacritized keys in _PHON_DICT.
  const bare = ar.replace(/[\u064B-\u0652\u0670]/g, '');
  if (_PHON_DICT[bare]) return _PHON_DICT[bare];
  // Try without ال prefix
  if (bare.startsWith('ال') && _PHON_DICT[bare.slice(2)]) return 'Al-' + _PHON_DICT[bare.slice(2)];
  // Fallback: character-by-character with basic vowel insertion
  const cmap = {
    'أ':'A','إ':'I','آ':'Aa','ا':'a','ب':'b','ت':'t','ث':'th',
    'ج':'j','ح':'h','خ':'kh','د':'d','ذ':'dh','ر':'r','ز':'z',
    'س':'s','ش':'sh','ص':'s','ض':'d','ط':'t','ظ':'dh',
    'ع':'a','غ':'gh','ف':'f','ق':'q','ك':'k','ل':'l','م':'m',
    'ن':'n','ه':'h','و':'u','ي':'i','ة':'a','ى':'a',
    'ء':'','ئ':'i','ؤ':'u'
  };
  const vowels = 'aiuAIU';
  let out = '';
  const chars = [...ar];
  for (let i = 0; i < chars.length; i++) {
    const ch = chars[i];
    if (ch === ' ') { out += ' '; continue; }
    if (ch === 'ـ' || '\u064B\u064C\u064D\u064E\u064F\u0650\u0651\u0652'.includes(ch)) continue;
    const r = cmap[ch];
    if (r !== undefined) out += r;
  }
  return out.replace(/(^|\s)\S/g, c => c.toUpperCase()).trim() || ar;
}

